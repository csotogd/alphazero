from typing import Protocol, TypeVar, Any
import numpy as np

State = TypeVar('State')
class Game(Protocol[State]):
    """Deterministic, alternating, two-player, perfect-information zero-sum game.

    States must be immutable. Players are 0/1. Values are always relative to the
    player to move in that state, including at terminal states. Actions are stable
    integers in [0, action_size); masks must include all and only legal actions.
    Each adapter supplies Markov-complete CHW features (not hidden heuristics).
    """
    name: str
    action_size: int
    observation_shape: tuple[int, int, int]
    max_moves: int
    def initial_state(self) -> State: ...
    def current_player(self, state: State) -> int: ...
    def legal_actions(self, state: State) -> np.ndarray: ...
    def next_state(self, state: State, action: int) -> State: ...
    def terminal_value(self, state: State) -> float | None: ...
    def encode(self, state: State) -> np.ndarray: ...
    def serialize(self, state: State) -> dict[str, Any]: ...
    def decode_action(self, action: int) -> dict[str, Any]: ...
